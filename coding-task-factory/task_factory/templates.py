def build_spec(seed: int) -> TaskSpec:
    rng = random.Random(seed)
    builder = rng.choice(BUILDERS)
    spec = _add_meaningful_variant(builder(seed, rng), rng)
    # Generated Go source is always formatted deterministically by the factory.
    if not re.search(r"^package fraudguard$", spec.test_source, re.MULTILINE):
        raise ValueError(f"template {spec.family} produced invalid Go test source")
    return spec


