import argparse
import json
import sys
from pathlib import Path

from .factory import FactoryError
from .harbor_runner import run_agent_benchmark, run_harbor_validation
from .portfolio import generate_portfolio
from .scanner import format_scan_report, scan_repository
from .seed_comparison import generate_seed_comparison
from .seed_runs import (
    generate_seeded_run,
    watch_target,
)
from .targets import TargetError
from .validation import ValidationError, validate_task
from .variation import compare_task_packages, render_comparison


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="task-factory",
        description="Generate and validate reproducible coding tasks offline.",
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    generate = subparsers.add_parser("generate", help="create a seeded task package")
    generate.add_argument(
        "--target",
        required=True,
        help="local Git checkout to archive at its pinned commit",
    )
    generate.add_argument("--seed", type=int, help="integer seed for selected mode")
    generate.add_argument(
        "--seed-mode",
        choices=("selected", "auto"),
        help="selected requires --seed; auto derives a seed from the commit and patch",
    )
    generate.add_argument(
        "--auto-seed",
        action="store_true",
        help="alias for --seed-mode auto",
    )
    generate.add_argument("--out", required=True, help="new or empty task output directory")
    generate.add_argument(
        "--blueprint",
        help="language-neutral task blueprint directory for any repository language",
    )
    generate.add_argument("--patch-file", help="optional patch whose digest influences auto-seed")
    generate.add_argument("--log", default="runs/seed_log.jsonl")
    generate.add_argument(
        "--local-validation",
        action="store_true",
        help="run isolated local preflight in selected mode (always runs in auto mode)",
    )
    generate.add_argument("--timeout", type=int, default=180)

    watch = subparsers.add_parser(
        "watch",
        help="poll a local target and auto-process each new commit or tracked patch once",
    )
    watch.add_argument("--target", required=True, help="local target Git checkout")
    watch.add_argument("--out-root", default="runs/auto-tasks")
    watch.add_argument("--log", default="runs/seed_log.jsonl")
    watch.add_argument("--interval", type=float, default=5)
    watch.add_argument("--timeout", type=int, default=180)
    watch.add_argument(
        "--once",
        action="store_true",
        help="process the current target state once, then exit",
    )

    portfolio = subparsers.add_parser(
        "portfolio",
        help="generate a novelty-aware set of distinct bundled task variants",
    )
    portfolio.add_argument(
        "--target",
        required=True,
        help="local FraudGuard Git checkout to archive at a pinned commit",
    )
    portfolio.add_argument("--seed-start", type=int, default=0)
    portfolio.add_argument("--count", type=int, default=6)
    portfolio.add_argument("--search-limit", type=int, default=10_000)
    portfolio.add_argument("--out", required=True, help="new or empty portfolio directory")

    compare = subparsers.add_parser(
        "compare",
        help="write a side-by-side variation report and flag repeated profiles",
    )
    comparison_source = compare.add_mutually_exclusive_group(required=True)
    comparison_source.add_argument(
        "--tasks",
        nargs="+",
        help="at least two generated task package directories",
    )
    comparison_source.add_argument(
        "--seeds",
        nargs="+",
        type=int,
        help="generate and compare at least two selected integer seeds",
    )
    compare.add_argument("--target", help="target Git checkout required with --seeds")
    compare.add_argument(
        "--out-root",
        help="new or empty directory for packages generated by --seeds",
    )
    compare.add_argument("--blueprint", help="optional language-neutral task blueprint")
    compare.add_argument("--log", default="runs/seed_log.jsonl")
    compare.add_argument("--timeout", type=int, default=180)
    compare.add_argument("--out", help="optional Markdown report destination")
    compare.add_argument("--json-out", help="optional machine-readable JSON report destination")

    scan = subparsers.add_parser(
        "scan",
        help="detect languages, manifests, and likely native test commands",
    )
    scan.add_argument("--target", required=True, help="local Git checkout to inspect")
    scan.add_argument("--format", choices=("text", "json"), default="text")

    validate = subparsers.add_parser(
        "validate",
        help="run Harbor nop and oracle trials and record reward evidence",
    )
    validate.add_argument("--task", required=True, help="generated task package directory")
    validate.add_argument("--jobs-dir", help="directory for Harbor job and trial outputs")
    validate.add_argument("--harbor-bin", default="harbor", help="Harbor executable (default: harbor)")
    validate.add_argument(
        "--timeout",
        type=int,
        default=7200,
        help="timeout for each Harbor job in seconds (default: 7200)",
    )

    preflight = subparsers.add_parser(
        "preflight",
        help="run a local diagnostic against the embedded source snapshot; not a validity gate",
    )
    preflight.add_argument("--task", required=True, help="generated task package directory")
    preflight.add_argument("--timeout", type=int, default=180)

    agent_run = subparsers.add_parser(
        "agent-run",
        help="opt in to real Harbor coding-agent trials after Harbor validation",
    )
    agent_run.add_argument("--task", required=True, help="Harbor task package directory")
    agent_run.add_argument("--agent", required=True, help="Harbor pre-integrated agent name")
    agent_run.add_argument("--model", required=True, help="provider/model identifier")
    agent_run.add_argument("--attempts", type=int, default=1, help="number of fresh trials")
    agent_run.add_argument("--jobs-dir", help="directory for Harbor job and trial outputs")
    agent_run.add_argument("--harbor-bin", default="harbor", help="Harbor executable")
    agent_run.add_argument("--timeout", type=int, default=14400)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    try:
        if args.command == "scan":
            result = scan_repository(args.target)
            if args.format == "json":
                print(json.dumps(result, indent=2, sort_keys=True))
            else:
                print(format_scan_report(result), end="")
            return 0

        if args.command == "generate":
            if args.timeout < 1:
                raise ValidationError("timeout must be a positive number of seconds")
            if args.auto_seed and args.seed_mode == "selected":
                raise FactoryError("--auto-seed conflicts with --seed-mode selected")
            if args.auto_seed and args.seed is not None:
                raise FactoryError("--auto-seed cannot be combined with --seed")
            seed_mode = args.seed_mode or ("auto" if args.auto_seed else "selected")
            if seed_mode == "auto" and args.seed is not None:
                raise FactoryError("auto seed mode must not include --seed")
            if seed_mode == "selected" and args.seed is None:
                raise FactoryError("selected seed mode requires --seed")
            result = generate_seeded_run(
                args.target,
                args.out,
                seed_mode=seed_mode,
                selected_seed=args.seed,
                blueprint_dir=args.blueprint,
                patch_file=args.patch_file,
                log_path=args.log,
                local_validation=(
                    True if args.local_validation else (True if seed_mode == "auto" else False)
                ),
                timeout=args.timeout,
            )
            local_validation = result.get("local_validation") or {}
            print(
                json.dumps(
                    {
                        "package_path": result["package_path"],
                        "seed_mode": result["seed_mode"],
                        "seed": result["seed"],
                        "seed_reference": result["seed_reference"],
                        "local_validation_status": local_validation.get("status", "not_run"),
                        "coverage": local_validation.get("coverage"),
                        "harbor_status": "pending",
                        "seed_log": result["log_path"],
                    },
                    indent=2,
                    sort_keys=True,
                )
            )
            return 0

        if args.command == "watch":
            if args.timeout < 1:
                raise ValidationError("timeout must be a positive number of seconds")
            result = watch_target(
                args.target,
                args.out_root,
                log_path=args.log,
                interval_seconds=args.interval,
                timeout=args.timeout,
                once=args.once,
                on_record=(
                    None
                    if args.once
                    else lambda record: print(
                        json.dumps(record, sort_keys=True), flush=True
                    )
                ),
            )
            if args.once:
                print(json.dumps(result, indent=2, sort_keys=True))
            return 0

        if args.command == "portfolio":
            result = generate_portfolio(
                args.target,
                args.seed_start,
                args.count,
                args.out,
                args.search_limit,
            )
            print(json.dumps(result, indent=2, sort_keys=True))
            print("Portfolio task packages remain not validated until Harbor trials run.")
            return 0

        if args.command == "compare":
            if args.seeds is not None:
                if not args.target:
                    raise FactoryError("--target is required with --seeds")
                if not args.out_root:
                    raise FactoryError("--out-root is required with --seeds")
                result = generate_seed_comparison(
                    args.target,
                    args.seeds,
                    args.out_root,
                    blueprint_dir=args.blueprint,
                    log_path=args.log,
                    timeout=args.timeout,
                )
            else:
                if args.target or args.out_root or args.blueprint:
                    raise FactoryError(
                        "--target, --out-root, and --blueprint are only used with --seeds"
                    )
                result = compare_task_packages(args.tasks)
            report = render_comparison(result)
            if args.out:
                destination = Path(args.out).expanduser().resolve()
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_text(report, encoding="utf-8", newline="\n")
                print(f"Variation comparison written to: {destination}")
            else:
                print(report, end="")
            if args.json_out:
                destination = Path(args.json_out).expanduser().resolve()
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_text(
                    json.dumps(result, indent=2, sort_keys=True) + "\n",
                    encoding="utf-8",
                    newline="\n",
                )
                print(f"JSON comparison written to: {destination}")
            if result["likely_clone_groups"]:
                print("error: repeated semantic variation profiles detected", file=sys.stderr)
                return 1
            return 0

        if args.command == "preflight":
            if args.timeout < 1:
                raise ValidationError("timeout must be a positive number of seconds")
            result = validate_task(args.task, timeout=args.timeout)
            print(json.dumps(result, indent=2, sort_keys=True))
            return 0 if result.get("status") == "passed" else 2

        if args.command == "validate":
            if args.timeout < 1:
                raise ValidationError("timeout must be a positive number of seconds")
            result = run_harbor_validation(
                args.task,
                args.jobs_dir,
                harbor_bin=args.harbor_bin,
                timeout=args.timeout,
            )
            print(json.dumps(result, indent=2, sort_keys=True))
            return 0 if result.get("status") == "valid" else 2

        if args.command == "agent-run":
            if args.timeout < 1:
                raise ValidationError("timeout must be a positive number of seconds")
            result = run_agent_benchmark(
                args.task,
                args.agent,
                args.model,
                args.attempts,
                args.jobs_dir,
                harbor_bin=args.harbor_bin,
                timeout=args.timeout,
            )
            print(json.dumps(result, indent=2, sort_keys=True))
            return 0 if result.get("status") == "completed" else 2

        raise ValueError(f"unknown command: {args.command}")
    except (FactoryError, TargetError, ValidationError, OSError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
